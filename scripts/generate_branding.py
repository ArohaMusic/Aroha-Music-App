#!/usr/bin/env python3
"""Generate native branding from the reviewed Vinyl Headset SVG.

Standard-library generation: python3 scripts/generate_branding.py
Also render committed PNGs: python3 scripts/generate_branding.py --png
PNG rendering requires CairoSVG in a separate development environment only.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/branding"
DRAWABLE = ROOT / "app/src/main/res/drawable"
RED = "#E61E1E"
LABEL = "#B51220"
WHITE = "#FFFFFF"
SVG = "http://www.w3.org/2000/svg"


def svg_art(arch: str, ear: str, label: str, *, background: bool, monochrome: bool = False) -> str:
    foreground = WHITE if background else RED
    backdrop = f'<rect width="100" height="100" fill="{RED}"/>' if background else ""
    record = ("" if monochrome else f'<path fill="{LABEL}" d="{label}"/>') + f'<path fill="{foreground}" fill-rule="evenodd" d="{ear}"/>'
    return f'''<svg xmlns="{SVG}" width="1024" height="1024" viewBox="0 0 100 100">
<title>Aroha Music — Vinyl Headset {'app icon' if background else 'symbol'}</title>
{backdrop}
<path fill="{foreground}" d="{arch}"/>
<g>{record}</g>
<g transform="translate(100 0) scale(-1 1)">{record}</g>
</svg>
'''


def vector(arch: str, ear: str, label: str, *, adaptive: bool, monochrome: bool, size: int, background: bool = False) -> str:
    def path(data: str, color: str, even_odd: bool = False) -> str:
        fill = ' android:fillType="evenOdd"' if even_odd else ""
        return f'<path android:fillColor="{color}"{fill} android:pathData="{data}"/>'
    record = ("" if monochrome else path(label, LABEL)) + path(ear, WHITE, True)
    scale, offset = ("0.72", "18") if adaptive else ("1.08", "0")
    backdrop = path("M0 0 H108 V108 H0 Z", RED) if background else ""
    return f'''<!-- Generated by scripts/generate_branding.py; edit assets/branding/aroha-vinyl-headset.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{size}dp" android:height="{size}dp" android:viewportWidth="108" android:viewportHeight="108">
{backdrop}
    <group android:scaleX="{scale}" android:scaleY="{scale}" android:translateX="{offset}" android:translateY="{offset}">
        {path(arch, WHITE)}
        <group>{record}</group>
        <group android:scaleX="-1" android:translateX="100">{record}</group>
    </group>
</vector>
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--png", action="store_true")
    args = parser.parse_args()
    source = ET.parse(ASSETS / "aroha-vinyl-headset.svg").getroot()
    paths = {p.attrib["id"]: p.attrib["d"] for p in source.iter(f"{{{SVG}}}path")}
    arch, ear, label = (paths[key] for key in ("arch", "earcup", "label"))
    outputs = {
        "aroha-music-icon.svg": svg_art(arch, ear, label, background=True),
        "aroha-music-logo.svg": svg_art(arch, ear, label, background=False, monochrome=True),
    }
    destinations = (ASSETS,)
    for folder in destinations:
        folder.mkdir(parents=True, exist_ok=True)
        for name, contents in outputs.items():
            (folder / name).write_text(contents)
    for name, adaptive, monochrome, size in (
        ("brand_foreground.xml", True, False, 108),
        ("brand_monochrome.xml", True, True, 108),
        ("brand_mark.xml", False, True, 48),
        ("ic_aroha.xml", False, True, 24),
    ):
        (DRAWABLE / name).write_text(vector(arch, ear, label, adaptive=adaptive, monochrome=monochrome, size=size))
    (DRAWABLE / "brand_icon.xml").write_text(vector(arch, ear, label, adaptive=False, monochrome=False, size=48, background=True))
    (DRAWABLE / "brand_background.xml").write_text(f'''<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="{RED}" />
</shape>
''')
    if args.png:
        import cairosvg
        for stem in ("aroha-music-icon", "aroha-music-logo"):
            output = ASSETS / f"{stem}.png"
            cairosvg.svg2png(bytestring=outputs[f"{stem}.svg"].encode(), write_to=str(output), output_width=1024, output_height=1024)
    print("Generated Android vectors and SVG branding" + (" and PNG exports." if args.png else "."))


if __name__ == "__main__":
    main()
